-- 12_triggers.sql: Trigger-Driven Automated Events
SET LINESIZE 160 PAGESIZE 50 FEEDBACK ON;
PROMPT ============================================================;
PROMPT 1. RESTOCK EVENTS (Generated by TRG_STOCK_THRESHOLD_ALERT)
PROMPT ============================================================;
COLUMN restock_id FORMAT 9999 HEADING "ID";
COLUMN product_name FORMAT A26 HEADING "PRODUCT";
COLUMN from_loc FORMAT A14 HEADING "FROM_LOC";
COLUMN to_loc FORMAT A14 HEADING "TO_LOC";
COLUMN quantity_moved FORMAT 9999 HEADING "QTY";
COLUMN status FORMAT A10 HEADING "STATUS";

SELECT r.restock_id, SUBSTR(p.product_name, 1, 26) AS product_name,
       lf.location_code AS from_loc, lt.location_code AS to_loc,
       r.quantity_moved, r.status
FROM RestockEvent r
JOIN Product p ON r.product_id = p.product_id
JOIN InventoryLocation lf ON r.from_location_id = lf.location_id
JOIN InventoryLocation lt ON r.to_location_id = lt.location_id
WHERE ROWNUM <= 4;

PROMPT ============================================================;
PROMPT 2. REORDER TRIGGERS (Generated by TRG_STOCK_THRESHOLD_ALERT)
PROMPT ============================================================;
COLUMN trigger_id FORMAT 9999 HEADING "ID";
COLUMN product_name FORMAT A26 HEADING "PRODUCT";
COLUMN location_code FORMAT A14 HEADING "LOCATION";
COLUMN stock_at_trigger FORMAT 9999 HEADING "STOCK";
COLUMN threshold_at_trigger FORMAT 9999 HEADING "THRESH";
COLUMN status FORMAT A10 HEADING "STATUS";

SELECT rt.trigger_id, SUBSTR(p.product_name, 1, 26) AS product_name,
       loc.location_code,
       rt.stock_at_trigger, rt.threshold_at_trigger, rt.status
FROM ReorderTrigger rt
JOIN Product p ON rt.product_id = p.product_id
JOIN InventoryLocation loc ON rt.location_id = loc.location_id
WHERE ROWNUM <= 4;

